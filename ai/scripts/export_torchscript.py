"""
TorchScript 내보내기 스크립트 (trace)

사용법:
    python scripts/export_torchscript.py --weights models/efficientnetv2s_3class_v2.0.0.pth --metadata models/efficientnetv2s_3class_v2.0.0_metadata.json
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import torch
import torch.nn as nn
from torchvision.models import efficientnet_v2_s

PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from config import IMAGE_SIZE


def build_model(num_classes: int = 3) -> nn.Module:
    model = efficientnet_v2_s(weights=None)
    in_features = model.classifier[1].in_features
    model.classifier[1] = nn.Linear(in_features, num_classes)
    return model


def export_torchscript(weights_path: str, output_path: str, metadata_path: str):
    model = build_model(num_classes=3)
    state = torch.load(weights_path, map_location="cpu")
    model.load_state_dict(state, strict=True)
    model.eval()

    dummy = torch.zeros(1, 3, IMAGE_SIZE[1], IMAGE_SIZE[0])
    traced = torch.jit.trace(model, dummy)
    traced.save(output_path)

    if metadata_path:
        output_meta = Path(output_path).with_suffix("").with_name(Path(output_path).stem + "_metadata.json")
        with open(metadata_path, "r", encoding="utf-8") as f:
            metadata = json.load(f)
        with open(output_meta, "w", encoding="utf-8") as f:
            json.dump(metadata, f, indent=2)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Export EfficientNetV2-S TorchScript (trace)")
    parser.add_argument("--weights", required=True, help="Path to .pth weights")
    parser.add_argument("--output", default=None, help="Output .pt path (autogenerated if not specified)")
    parser.add_argument("--metadata", default=None, help="Path to metadata json to copy")
    args = parser.parse_args()

    weights_path = Path(args.weights)
    metadata_path = args.metadata

    if not metadata_path:
        candidate_meta = weights_path.with_name(weights_path.stem + "_metadata.json")
        if candidate_meta.exists():
            metadata_path = str(candidate_meta)

    output_path = args.output
    if not output_path:
        version = None
        
        if metadata_path and Path(metadata_path).exists():
            try:
                import json
                with open(metadata_path, "r", encoding="utf-8") as f:
                    meta = json.load(f)
                    version = meta.get("version")
            except Exception:
                pass
        
        if not version:
            import re
            match = re.search(r"_v(\d+\.\d+\.\d+)", weights_path.name)
            if match:
                version = match.group(1)
        
        if version:
            output_path = str(weights_path.parent / f"efficientnetv2s_3class_traced_v{version}.pt")
        else:
            output_path = "models/efficientnetv2s_3class_traced.pt"

    export_torchscript(args.weights, output_path, metadata_path)
    print(f"TorchScript saved: {output_path}")
